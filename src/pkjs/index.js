// Phone side: Clay builds the settings page (gear icon in the Pebble app)
// from config.js and sends the chosen values to the watch.
var Clay = require('@rebble/clay');
var clayConfig = require('./config');
var customClay = require('./custom-clay');
var clayComponents = require('./clay-components');
var previews = require('./previews');  // generated by tools/screenshots.py

// We open the page and receive its result ourselves (Clay's documented
// "autoHandleEvents: false" mode) so the page also works in the emulator.
var clay = new Clay(clayConfig, customClay, { autoHandleEvents: false });
// The accent color grid, the picture choices and the Restore defaults / Save row.
clayComponents.forEach(function (component) {
  clay.registerComponent(component);
});

// A copy of config.js in which every option that names a `preview` has that
// picture for this watch platform (from previews.js). Only the connected
// watch's pictures go into the page, which keeps it small. config.js is plain
// data, so a JSON round trip makes a full copy.
function configFor(platform) {
  var pictures = previews[platform] || {};
  var config = JSON.parse(JSON.stringify(clayConfig));
  (function addPictures(items) {
    items.forEach(function (item) {
      if (item.items) {
        addPictures(item.items);
      }
      (item.options || []).forEach(function (option) {
        if (option.preview) {
          option.image = pictures[option.preview] || '';
        }
      });
    });
  })(config);
  return config;
}

// In the emulator (Pebble.platform === 'pypkjs') Clay sends its page through
// Pebble's old helper page on Amazon S3, which has been offline for years, so
// the browser shows an error instead of the settings. Give the emulator the
// page as a data: URL instead, and let the page read the return address that
// pebble-tool adds as ?return_to=... (the one job the old helper page did).
// On a phone the URL is left exactly as Clay makes it.
var CLAY_EMULATOR_HELPER = 'http://clay.pebble.com.s3-website-us-west-2.amazonaws.com/#';
var RETURN_TO_PLACEHOLDER = /(["'])\$\$RETURN_TO\$\$\1/;
var READ_RETURN_TO =
  '(function () {' +
  ' var m = /[?&]return_to=([^&]*)/.exec(location.search);' +
  " return m ? decodeURIComponent(m[1]) : 'pebblejs://close#';" +
  ' })()';

function emulatorUrl(url) {
  if (url.indexOf(CLAY_EMULATOR_HELPER) !== 0) {
    return url;
  }
  var html = decodeURIComponent(url.substring(CLAY_EMULATOR_HELPER.length));
  // A function as the replacement, so "$" in the page is never treated specially.
  html = html.replace(RETURN_TO_PLACEHOLDER, function () { return READ_RETURN_TO; });
  return 'data:text/html;charset=utf-8,' + encodeURIComponent(html);
}

Pebble.addEventListener('showConfiguration', function () {
  try {
    // What Clay's automatic mode does just before opening the page: the page
    // needs the watch's platform to decide which options to show.
    var watch = Pebble.getActiveWatchInfo && Pebble.getActiveWatchInfo();
    clay.meta.activeWatchInfo = watch;
    clay.meta.accountToken = Pebble.getAccountToken();
    clay.meta.watchToken = Pebble.getWatchToken();
    clay.config = configFor(watch && watch.platform);

    var url = clay.generateUrl();
    Pebble.openURL(Pebble.platform === 'pypkjs' ? emulatorUrl(url) : url);
  } catch (e) {
    // Shows up in `pebble logs`, instead of the page silently never opening.
    console.log('Decimal Time: could not open the settings page: ' + e + (e && e.stack ? '\n' + e.stack : ''));
  }
});

// Sending settings to the watch can fail, for example when the Bluetooth
// connection drops for a moment. The settings page has saved them on the
// phone by then, so a lost message would leave the page and the watch
// disagreeing. Each failed send is retried a few times; if it still fails,
// the settings are kept here and sent again when the face next starts (this
// JavaScript runs whenever the face does).
var SEND_ATTEMPTS = 3;
var RETRY_DELAY_MS = 2000;
var UNSENT_KEY = 'unsent-settings';

var sendRound = 0;     // a newer save makes the older one's retries stop
var retryTimer = null;

// localStorage can throw (storage full, or a damaged value), so every use is
// guarded: at worst a failed send is not retried at the next start.
function loadUnsent() {
  try {
    var text = localStorage.getItem(UNSENT_KEY);
    return text ? JSON.parse(text) : null;
  } catch (err) {
    return null;
  }
}

function saveUnsent(settings) {
  try {
    localStorage.setItem(UNSENT_KEY, JSON.stringify(settings));
  } catch (err) {
    console.log('Decimal Time: could not keep the settings for later: ' + err);
  }
}

function clearUnsent() {
  try {
    localStorage.removeItem(UNSENT_KEY);
  } catch (err) {
    // Nothing to do: the next start sends the same settings once more.
  }
}

function sendSettings(settings) {
  var round = ++sendRound;
  if (retryTimer) {
    clearTimeout(retryTimer);
    retryTimer = null;
  }
  saveUnsent(settings);

  function attempt(n) {
    Pebble.sendAppMessage(settings, function () {
      if (round === sendRound) {
        clearUnsent();
        console.log('Decimal Time: settings sent to the watch');
      }
    }, function (err) {
      if (round !== sendRound) {
        return;  // newer settings are on their way
      }
      if (n < SEND_ATTEMPTS) {
        console.log('Decimal Time: sending settings failed, trying again: ' + JSON.stringify(err));
        retryTimer = setTimeout(function () {
          retryTimer = null;
          attempt(n + 1);
        }, RETRY_DELAY_MS);
      } else {
        console.log('Decimal Time: sending settings failed; will try again when the face starts');
      }
    });
  }
  attempt(1);
}

Pebble.addEventListener('ready', function () {
  var unsent = loadUnsent();
  if (unsent) {
    sendSettings(unsent);
  }
});

Pebble.addEventListener('webviewclosed', function (e) {
  if (!e || !e.response) {
    return;  // closed without saving
  }
  var settings;
  try {
    settings = clay.getSettings(e.response);
  } catch (err) {
    console.log('Decimal Time: could not read the settings page result: ' + err);
    return;
  }
  sendSettings(settings);
});
